// 获取一级分类下的资料数量（自动计算）
export function getPlatformCategoryCount(categoryId) {
	const category = platformKnowledgeCategories.find((c) => c.id === categoryId);
	if (!category) return 0;
	// 锁定的卡片使用固定统计
	if (category.locked && category.countOverride != null) return category.countOverride;
	// 其余根据实际数据计算
	return platformKnowledgeItems.filter((item) => item.knowledgeCategory === categoryId).length;
}

// 获取二级分类下的资料数量
export function getSubCatalogCount(knowledgeCategoryId, subCatalogId) {
	return platformKnowledgeItems.filter(
		(item) => item.knowledgeCategory === knowledgeCategoryId && item.category === subCatalogId,
	).length;
}

// 获取某个一级分类下的总资料数
export function getKnowledgeCategoryTotal(knowledgeCategoryId) {
	return platformKnowledgeItems.filter((item) => item.knowledgeCategory === knowledgeCategoryId).length;
}

// 平台知识搜索
export function searchPlatformKnowledge(keyword, knowledgeCategoryId) {
	if (!keyword) {
		return platformKnowledgeItems.filter((item) => item.knowledgeCategory === knowledgeCategoryId);
	}
	const lower = keyword.toLowerCase().trim();
	return platformKnowledgeItems.filter((item) => {
		if (item.knowledgeCategory !== knowledgeCategoryId) return false;
		const fields = [
			item.title,
			item.description,
			item.author,
			item.publisher,
			item.standardNo,
			...(item.keywords || []),
		].filter(Boolean);
		return fields.some((f) => String(f).toLowerCase().includes(lower));
	});
}

// 获取单个资料
export function getPlatformKnowledgeItemById(id) {
	return platformKnowledgeItems.find((item) => item.id === id);
}

