// 企业知识搜索
export function searchEnterpriseKnowledge(keyword, items) {
	const source = items || enterpriseKnowledgeItems;
	if (!keyword) return source;
	const lower = keyword.toLowerCase().trim();
	return source.filter((item) => {
		const fields = [item.title, item.description, item.categoryName, item.source, ...(item.tags || [])].filter(
			Boolean,
		);
		return fields.some((f) => String(f).toLowerCase().includes(lower));
	});
}

// 获取企业分类数量（自动计算）
export function getEnterpriseCategoryCount(categoryId, items) {
	const source = items || enterpriseKnowledgeItems;
	if (categoryId === "all") return source.length;
	return source.filter((item) => item.categoryId === categoryId).length;
}
